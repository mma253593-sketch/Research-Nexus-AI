-- =====================================================================
--  V2.0 bundler: assembles the paste-ready QCS scripts from src/.
--  Usage (from anywhere): lua5.3 qcs/v2_rebuild/scripts/build.lua
--  Outputs:
--    dist/XAUUSD_Smart_Entry_V2_0.lua        chart overlay (arrows)   <= 25,000 characters
--    dist/XAUUSD_Smart_Entry_V2_0_Panel.lua  separate pane (scores)   <= 25,000 characters
--    dist/readable/XAUUSD_Smart_Entry_V2_0_Readable.lua  same code with comments and
--        original names, for reading/review only (too long to paste)
--  The build FAILS if a paste-ready script exceeds 25,000 characters.
--
--  Steps for the paste-ready scripts (all behaviour-preserving):
--    1 bundle: each module becomes a function in a registry resolved by a
--      LOCAL `require` (no runtime `require` needed);
--      QCS variant: "@qcs-strip" regions removed, "--@qcs:" lines enabled
--    2 minify: comments and redundant whitespace removed
--    3 shrink: consistent renaming of identifiers / internal code strings
--    4 join:   engine lines joined; QCS adapter + view keep one statement per line
--  test/test_qcs_bundle.lua proves the paste-ready scripts reproduce the
--  pure engine bar by bar, that Readable = paste-ready, and the size limit.
-- =====================================================================
local root = (arg and arg[0] or ""):match ("^(.*)/scripts/[^/]*$") or V2_ROOT or "."

LIMIT = 25000
M_ORDER = { "util", "default_config", "config", "indicators", "data_validation", "regime_detection",
            "trend_context", "momentum_analysis", "price_action", "entry_timing", "volatility_filter",
            "adaptive_profile", "signal_engine", "diagnostics", "main" }
local PATH = { default_config = "config/default_config.lua" }

local function read (p)
    local f = assert (io.open (root .. "/" .. p, "r"), "cannot read " .. p)
    local s = f:read ("a"); f:close (); return s
end
local function write (p, s)
    local f = assert (io.open (root .. "/" .. p, "w"), "cannot write " .. p)
    f:write (s); f:close ()
end

--- QCS variant of a source: drops "@qcs-strip" regions, enables "--@qcs:" lines
function qcs_variant (text)
    local out, skip = {}, false
    for line in (text .. "\n"):gmatch ("([^\n]*)\n") do
        if line:match ("^%s*%-%- @qcs%-strip%-begin") then assert (not skip, "nested @qcs-strip-begin"); skip = true
        elseif line:match ("^%s*%-%- @qcs%-strip%-end") then assert (skip, "@qcs-strip-end without begin"); skip = false
        elseif not skip then
            local code = line:match ("^%s*%-%-@qcs: (.*)$")
            out[#out + 1] = code or line
        end
    end
    assert (not skip, "unterminated @qcs-strip region")
    return table.concat (out, "\n")
end

function bundle (header, view)
    local out = { header,
        "-- Generated by qcs/v2_rebuild/scripts/build.lua from qcs/v2_rebuild/src. Edit the sources, not this file.",
        "-- XAUUSD Smart Entry V2.0 - Adaptive Precision Engine. Signal generation only; never places trades.",
        "local __mods, __done = {}, {}",
        "local function require (name)",
        "    local v = __done[name]",
        "    if v == nil then v = __mods[name] (); __done[name] = v end",
        "    return v",
        "end" }
    for _, m in ipairs (M_ORDER) do
        out[#out + 1] = ('__mods["%s"] = function ()'):format (m)
        out[#out + 1] = (qcs_variant (read (PATH[m] or ("src/" .. m .. ".lua"))):gsub ("%s+$", ""))
        out[#out + 1] = "end"
    end
    out[#out + 1] = (read ("src/qcs/adapter.lua"):gsub ("%s+$", ""))
    out[#out + 1] = (read ("src/qcs/" .. view):gsub ("%s+$", ""))
    return table.concat (out, "\n") .. "\n"
end

--- removes comments outside string literals, then collapses whitespace.
--- No long strings / long comments are used in the sources (checked here).
PUNCT = "[%(%)%[%]{},=<>~%+%-%*/;:#%^%%]"
function minify (text)
    assert (not text:find ("%[%[") and not text:find ("%-%-%["), "long strings/comments not supported by minify")
    local out = {}
    for line in (text .. "\n"):gmatch ("([^\n]*)\n") do
        local s, q, i = {}, nil, 1
        line = line:gsub ("^%s+", ""):gsub ("%s+$", "")
        while i <= #line do
            local c = line:sub (i, i)
            if q then
                s[#s + 1] = c
                if c == "\\" then s[#s + 1] = line:sub (i + 1, i + 1); i = i + 1
                elseif c == q then q = nil end
            elseif c == '"' or c == "'" then q = c; s[#s + 1] = c
            elseif line:sub (i, i + 1) == "--" then break
            elseif c:match ("%s") then
                local p, n = s[#s] or "", line:sub (i + 1, i + 1)
                if p ~= " " and not (p:match (PUNCT) or n:match (PUNCT) or n:match ("%s")) then s[#s + 1] = " "
                elseif p == "-" and n == "-" then s[#s + 1] = " " end
            else s[#s + 1] = c end
            i = i + 1
        end
        local l = table.concat (s):gsub ("%s+$", "")
        if l ~= "" then out[#out + 1] = l end
    end
    return table.concat (out, "\n") .. "\n"
end

-- ---------------------------------------------------------------------
--  shrink: consistent whole-bundle renaming to short names (applied to
--  minified text, which has no comments).
--  NEVER renamed: Lua keywords, every name of the Lua standard library,
--  the QCS API names used by the adapter/views, the globals read by the
--  views/tests, and any identifier that also appears as a string literal,
--  EXCEPT module names and ALL-CAPS internal codes (reasons, setups,
--  regimes), which are renamed together in both forms. Chart labels and
--  values checked by tests are excluded from that.
-- ---------------------------------------------------------------------
local KEEP = {}
for w in ([[and break do else elseif end false for function goto if in local nil not or repeat return then true until while
    self arg _G _ENV _VERSION __index __newindex __call __add __sub __mul __div __unm __lt __le __eq __len __tostring __mode
    instrument name short_name overlay input input_group integer double boolean color plot_visibility default type
    get_value make_series set open high low close time plot plot_shape hline rgba shape_style shape_size shape_location
    arrowup arrowdown belowbar abovebar circle tiny large normal huge small top xcross diamond
    SIG_DIR SIG_SCORE SIG_SETUP SIG_KIND CALL_SCORE PUT_SCORE TIME_SOURCE WAIT_REASON REGIME_CODE DATA_OK V2
    v2_window v2_cooldown v2_time v2_show_setup v2_call_color v2_put_color]]):gmatch ("[%w_]+") do KEEP[w] = true end
for k, v in pairs (_G) do
    KEEP[k] = true
    if type (v) == "table" then for k2 in pairs (v) do if type (k2) == "string" then KEEP[k2] = true end end end
end
local EXCL = { CALL = true, PUT = true, WAIT = true, XAUUSD = true, INDEX_PROXY = true,
               INDEX_PROXY_FALLBACK = true, TIME_SERIES = true }

local function tokens (text)            -- -> list of { kind = "id"|"str"|"num"|"other", s = ... }
    local out, i, n = {}, 1, #text
    while i <= n do
        local c = text:sub (i, i)
        if c == '"' or c == "'" then
            local j = i + 1
            while j <= n do
                local d = text:sub (j, j)
                if d == "\\" then j = j + 2 elseif d == c then break else j = j + 1 end
            end
            out[#out + 1] = { kind = "str", s = text:sub (i, j) }; i = j + 1
        elseif c:match ("%d") or (c == "." and text:sub (i + 1, i + 1):match ("%d")) then
            local s = text:match ("^0[xX]%x+", i) or text:match ("^%d*%.?%d+[eE][%+%-]?%d+", i)
                or text:match ("^%d+%.?%d*[eE][%+%-]?%d+", i) or text:match ("^%d*%.?%d+", i) or text:match ("^%d+%.?", i)
            out[#out + 1] = { kind = "num", s = s }; i = i + #s
        elseif c:match ("[%a_]") then
            local s = text:match ("^[%a_][%w_]*", i)
            out[#out + 1] = { kind = "id", s = s }; i = i + #s
        else
            out[#out + 1] = { kind = "other", s = c }; i = i + 1
        end
    end
    return out
end

function shrink (text)
    local toks = tokens (text)
    local count, all, strs = {}, {}, {}
    for _, t in ipairs (toks) do
        if t.kind == "id" then count[t.s] = (count[t.s] or 0) + 1; all[t.s] = true
        elseif t.kind == "str" then strs[t.s:sub (2, -2)] = true end
    end
    -- string constants renamed together with same-named identifiers
    local REN = {}
    for _, m in ipairs (M_ORDER) do REN[m] = true end
    for s in pairs (strs) do
        if s:match ("^[A-Z][A-Z0-9_]+$") and #s >= 4 and not EXCL[s] and not KEEP[s] then REN[s] = true end
    end
    for s in pairs (REN) do strs[s] = nil end
    for _, t in ipairs (toks) do
        local s = t.kind == "str" and t.s:sub (2, -2)
        if s and REN[s] then count[s] = (count[s] or 0) + 1 end
    end
    local cand = {}
    for id in pairs (count) do
        if not KEEP[id] and not strs[id] and #id > 2 then cand[#cand + 1] = id end
    end
    table.sort (cand, function (a, b)
        local sa, sb = (#a - 2) * count[a], (#b - 2) * count[b]
        if sa ~= sb then return sa > sb end
        return a < b
    end)
    local AL = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
    local AN = AL .. "0123456789_"
    local gen = {}
    for i = 1, #AL do gen[#gen + 1] = AL:sub (i, i) end
    for i = 1, #AL do for j = 1, #AN do gen[#gen + 1] = AL:sub (i, i) .. AN:sub (j, j) end end
    local function free (nm) return not (all[nm] or KEEP[nm] or strs[nm] or REN[nm]) end
    local map, gi = {}, 1
    for _, id in ipairs (cand) do
        while not free (gen[gi]) do gi = gi + 1 end
        if #gen[gi] < #id then map[id] = gen[gi]; gi = gi + 1 end
    end
    -- alias the math library (one local instead of ~50 x "math")
    while not free (gen[gi]) do gi = gi + 1 end
    local malias = gen[gi]
    map.math = malias
    local out = { "local " .. malias .. "=math\n" }
    for _, t in ipairs (toks) do
        local s = t.kind == "str" and t.s:sub (2, -2)
        local q = s and REN[s] and map[s]
        out[#out + 1] = (t.kind == "id" and map[t.s]) or (q and ('"' .. q .. '"')) or t.s
    end
    return table.concat (out)
end

--- joins lines: no separator next to punctuation, otherwise one space.
--- Never creates "--" (comment) or "[[" / "[=" (long bracket).
function join_lines (text)
    local out, prev = {}, nil
    for line in text:gmatch ("[^\n]+") do
        if prev == nil then out[1] = line
        else
            local a, b = prev:sub (-1), line:sub (1, 1)
            local glue = " "
            if (a:match (PUNCT) or b:match (PUNCT)) and not (a == "-" and b == "-") and not (a == "[" and (b == "[" or b == "=")) then glue = "" end
            out[#out + 1] = glue .. line
        end
        prev = line
    end
    return table.concat (out) .. "\n"
end

--- paste-ready form: header line kept, engine joined, QCS section one statement per line
function paste_ready (bundled)
    local first_line = bundled:match ("^[^\n]*")
    local body = shrink (minify (bundled:sub (#first_line + 2)))
    local cut = body:find ("\ninput_group", 1, true)
    assert (cut, "adapter section not found")
    return first_line .. "\n" .. join_lines (body:sub (1, cut)) .. body:sub (cut + 1)
end

CHART_HEADER = 'instrument { name = "XAUUSD Smart Entry V2.0", short_name = "XAU-SE2.0", overlay = true }'
PANEL_HEADER = 'instrument { name = "XAUUSD Smart Entry V2.0 Panel", short_name = "XAU-SE2.0 Panel", overlay = false }'

if BUILD_AS_LIBRARY then return end

local main = bundle (CHART_HEADER, "view_main.lua")
local panel = bundle (PANEL_HEADER, "view_panel.lua")
local chart, pane = paste_ready (main), paste_ready (panel)
os.remove (root .. "/dist/XAUUSD_Smart_Entry_V2_0_Main.lua")
os.remove (root .. "/dist/XAUUSD_Smart_Entry_V2_0_Mini.lua")
os.execute ("mkdir -p '" .. root .. "/dist/readable'")
write ("dist/XAUUSD_Smart_Entry_V2_0.lua", chart)
write ("dist/XAUUSD_Smart_Entry_V2_0_Panel.lua", pane)
write ("dist/readable/XAUUSD_Smart_Entry_V2_0_Readable.lua", main)
local fail = false
for _, x in ipairs ({ { "dist/XAUUSD_Smart_Entry_V2_0.lua", chart, true }, { "dist/XAUUSD_Smart_Entry_V2_0_Panel.lua", pane, true },
                      { "dist/readable/XAUUSD_Smart_Entry_V2_0_Readable.lua", main, false } }) do
    local lines = select (2, x[2]:gsub ("\n", ""))
    local note = x[3] and ((#x[2] <= LIMIT) and " <= 25,000 OK" or " EXCEEDS 25,000") or " (reference only, not for pasting)"
    print (("built %s (%d characters, %d lines)%s"):format (x[1], #x[2], lines, note))
    if x[3] and #x[2] > LIMIT then fail = true end
end
if fail then io.stderr:write ("error: a paste-ready script exceeds 25,000 characters\n"); os.exit (1) end
