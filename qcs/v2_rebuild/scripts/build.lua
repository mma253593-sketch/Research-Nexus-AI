-- =====================================================================
--  V2.0 bundler: assembles the paste-ready QCS scripts from src/.
--  Usage (from anywhere): lua5.3 qcs/v2_rebuild/scripts/build.lua
--  Outputs (dist/):
--    XAUUSD_Smart_Entry_V2_0_Main.lua   overlay arrows, readable (comments kept)
--    XAUUSD_Smart_Entry_V2_0_Panel.lua  separate pane: scores / regime
--    XAUUSD_Smart_Entry_V2_0_Mini.lua   Main without comments / extra spaces
--  Each module becomes a function in a registry; a LOCAL `require`
--  resolves them, so the bundle never depends on a runtime `require`.
--  Behavioural identity of Main and Mini is checked by test/test_qcs_bundle.lua.
-- =====================================================================
local root = (arg and arg[0] or ""):match ("^(.*)/scripts/[^/]*$") or "."

M_ORDER = { "util", "default_config", "config", "indicators", "data_validation", "regime_detection",
            "trend_context", "momentum_analysis", "price_action", "entry_timing", "volatility_filter",
            "adaptive_profile", "signal_engine", "diagnostics", "main" }
local PATH = { default_config = "config/default_config.lua" }

local function read (p)
    local f = assert (io.open (root .. "/" .. p, "r"), "cannot read " .. p)
    local s = f:read ("a"); f:close (); return s
end
local function write (p, s)
    local f = assert (io.open (root .. "/" .. p, "w"), "cannot write " .. p)
    f:write (s); f:close ()
end

local function bundle (header, view)
    local out = { header,
        "-- Generated by qcs/v2_rebuild/scripts/build.lua from qcs/v2_rebuild/src. Edit the sources, not this file.",
        "-- XAUUSD Smart Entry V2.0 - Adaptive Precision Engine. Signal generation only; never places trades.",
        "local __mods, __done = {}, {}",
        "local function require (name)",
        "    local v = __done[name]",
        "    if v == nil then v = __mods[name] (); __done[name] = v end",
        "    return v",
        "end" }
    for _, m in ipairs (M_ORDER) do
        out[#out + 1] = ('__mods["%s"] = function ()'):format (m)
        out[#out + 1] = (read (PATH[m] or ("src/" .. m .. ".lua")):gsub ("%s+$", ""))
        out[#out + 1] = "end"
    end
    out[#out + 1] = (read ("src/qcs/adapter.lua"):gsub ("%s+$", ""))
    out[#out + 1] = (read ("src/qcs/" .. view):gsub ("%s+$", ""))
    return table.concat (out, "\n") .. "\n"
end

--- removes comments outside string literals, then collapses whitespace.
--- No long strings / long comments are used in the sources (checked here).
local PUNCT = "[%(%)%[%]{},=<>~%+%-%*/;:#%^%%]"
function minify (text)
    assert (not text:find ("%[%[") and not text:find ("%-%-%["), "long strings/comments not supported by minify")
    local out = {}
    for line in (text .. "\n"):gmatch ("([^\n]*)\n") do
        local s, q, i = {}, nil, 1
        line = line:gsub ("^%s+", ""):gsub ("%s+$", "")
        while i <= #line do
            local c = line:sub (i, i)
            if q then
                s[#s + 1] = c
                if c == "\\" then s[#s + 1] = line:sub (i + 1, i + 1); i = i + 1
                elseif c == q then q = nil end
            elseif c == '"' or c == "'" then q = c; s[#s + 1] = c
            elseif line:sub (i, i + 1) == "--" then break
            elseif c:match ("%s") then
                local p, n = s[#s] or "", line:sub (i + 1, i + 1)
                if p ~= " " and not (p:match (PUNCT) or n:match (PUNCT) or n:match ("%s")) then s[#s + 1] = " "
                elseif p == "-" and n == "-" then s[#s + 1] = " " end
            else s[#s + 1] = c end
            i = i + 1
        end
        local l = table.concat (s):gsub ("%s+$", "")
        if l ~= "" then out[#out + 1] = l end
    end
    return table.concat (out, "\n") .. "\n"
end

local main = bundle ('instrument { name = "XAUUSD Smart Entry V2.0", short_name = "XAU-SE2.0", overlay = true }', "view_main.lua")
local panel = bundle ('instrument { name = "XAUUSD Smart Entry V2.0 Panel", short_name = "XAU-SE2.0 Panel", overlay = false }', "view_panel.lua")
local mini = minify (main)
write ("dist/XAUUSD_Smart_Entry_V2_0_Main.lua", main)
write ("dist/XAUUSD_Smart_Entry_V2_0_Panel.lua", panel)
write ("dist/XAUUSD_Smart_Entry_V2_0_Mini.lua", mini)
for _, x in ipairs ({ { "Main", main }, { "Panel", panel }, { "Mini", mini } }) do
    local lines = select (2, x[2]:gsub ("\n", ""))
    print (("built dist/XAUUSD_Smart_Entry_V2_0_%s.lua (%d characters, %d lines)"):format (x[1], #x[2], lines))
end
