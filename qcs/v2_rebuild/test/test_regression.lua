-- Requirement 22: regression. The decision stream of the engine on fixed
-- SYNTHETIC fixtures is pinned in test/golden.lua. An intentional change
-- of engine behaviour must regenerate it:
--   lua5.3 -e 'package.path="qcs/v2_rebuild/src/?.lua;qcs/v2_rebuild/config/?.lua;qcs/v2_rebuild/test/?.lua;qcs/v2_rebuild/eval/?.lua;"..package.path
--     io.write(require("test_regression").generate())' > qcs/v2_rebuild/test/golden.lua
-- and the change must be explained in the commit / CHANGELOG.
local C = require ("config")
local E = require ("main")
local F = require ("fixtures")
local csv = require ("csv")

local CASES = {
    { name = "mixed_s11", seg = "MIXED", seed = 11 },
    { name = "mixed_s23", seg = "MIXED", seed = 23 },
    { name = "up_s5", seg = "UP", seed = 5 },
    { name = "down_s5", seg = "DOWN", seed = 5 },
}

local function stream (case, cfg)
    local m1 = F.series (F[case.seg], case.seed)
    local run, parts, n = E.new_runner (cfg), {}, { CALL = 0, PUT = 0, WAIT = 0 }
    for Tn = 2, #m1 do
        local w = {}
        for j = math.max (1, Tn - 250), Tn - 1 do local b = m1[j]; w[#w + 1] = { t = b.t, o = b.o, h = b.h, l = b.l, c = b.c } end
        local r = run:step ({ now = m1[Tn].t, m1 = w })
        n[r.decision] = n[r.decision] + 1
        parts[#parts + 1] = r.decision:sub (1, 1) .. r.call_score .. "/" .. r.put_score .. ":" .. (r.reasons[1] or "")
    end
    return { calls = n.CALL, puts = n.PUT, waits = n.WAIT, fnv = csv.fnv1a (table.concat (parts, "\n")) }
end

local M = {}
function M.generate ()
    local cfg = assert (C.load ())
    local lines = { "-- generated by test_regression.lua (synthetic fixtures; engine " .. E.VERSION .. ")", "return {" }
    for _, c in ipairs (CASES) do
        local s = stream (c, cfg)
        lines[#lines + 1] = ('    %s = { calls = %d, puts = %d, waits = %d, fnv = "%s" },'):format (c.name, s.calls, s.puts, s.waits, s.fnv)
    end
    lines[#lines + 1] = "}"
    return table.concat (lines, "\n") .. "\n"
end

return setmetatable (M, { __call = function (_, T)
    local cfg = assert (C.load ())
    local ok, golden = pcall (require, "golden")
    T.case ("regression: golden file present", function () T.ok (ok, "test/golden.lua missing") end)
    if not ok then return end
    for _, c in ipairs (CASES) do
        T.case ("regression: decision stream unchanged on " .. c.name, function ()
            local s, g = stream (c, cfg), golden[c.name]
            T.ok (g ~= nil, "no golden entry")
            T.eq (s.calls, g.calls, "CALL count"); T.eq (s.puts, g.puts, "PUT count"); T.eq (s.waits, g.waits, "WAIT count")
            T.eq (s.fnv, g.fnv, "stream checksum")
        end)
    end
end })
